-- En-têtes de vente clôturées (annulées comprises, marquées), par jour × heure × magasin × vendeur × caissier × nature ×
-- prescription × catégorie : fréquentation, taux d'annulation, part tiers payant.
CREATE TABLE IF NOT EXISTS pilotage_vente_jour
(
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jour                    DATE        NOT NULL,
  heure                   SMALLINT    NOT NULL,
  magasin_id              INTEGER     NOT NULL,
  vendeur_id              INTEGER,
  caissier_id             INTEGER,
  nature_vente            VARCHAR(20),
  type_prescription       VARCHAR(20),
  categorie_ca            VARCHAR(20) NOT NULL,
  annulee                 BOOLEAN     NOT NULL,
  nb_ventes               BIGINT      NOT NULL,
  montant_ttc             BIGINT      NOT NULL,
  montant_ht              BIGINT      NOT NULL,
  montant_net             BIGINT      NOT NULL,
  remise                  BIGINT      NOT NULL,
  part_tiers_payant       BIGINT      NOT NULL,
  nb_ventes_client_connu  BIGINT      NOT NULL
);
CREATE INDEX IF NOT EXISTS pilotage_vente_jour_jour_idx ON pilotage_vente_jour (jour);

-- Commandes reçues, datées à la réception (décision du 2026-10-09), par jour × produit × fournisseur. Le prix d'achat est TTC :
-- le HT retire la taxe portée par la ligne (`order_line.tax_amount`).
CREATE TABLE IF NOT EXISTS pilotage_achat_jour
(
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jour               DATE    NOT NULL,
  produit_id         INTEGER NOT NULL,
  fournisseur_id     INTEGER NOT NULL,
  nb_bons            BIGINT  NOT NULL,
  quantite_commandee BIGINT  NOT NULL,
  quantite_recue     BIGINT  NOT NULL,
  quantite_gratuite  BIGINT  NOT NULL,
  montant_ht         BIGINT  NOT NULL,
  montant_ttc        BIGINT  NOT NULL
);
CREATE INDEX IF NOT EXISTS pilotage_achat_jour_jour_idx ON pilotage_achat_jour (jour);

-- Encaissements, par jour × type de transaction × mode × caissier × catégorie.
CREATE TABLE IF NOT EXISTS pilotage_encaissement_jour
(
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jour             DATE         NOT NULL,
  type_transaction VARCHAR(50)  NOT NULL,
  mode_paiement    VARCHAR(50),
  caissier_id      INTEGER,
  categorie_ca     VARCHAR(20),
  montant          BIGINT       NOT NULL,
  nb_transactions  BIGINT       NOT NULL
);
CREATE INDEX IF NOT EXISTS pilotage_encaissement_jour_jour_idx ON pilotage_encaissement_jour (jour);

-- Stock en fin de mois (stock + UG), par produit × magasin, valorisé à la date par fn_stock_valuation_bulk (V2.1.33) :
-- les mois passés se reconstituent depuis le journal des mouvements.
CREATE TABLE IF NOT EXISTS pilotage_stock_mensuel
(
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mois         DATE    NOT NULL,
  produit_id   INTEGER NOT NULL,
  magasin_id   INTEGER NOT NULL,
  quantite     BIGINT  NOT NULL,
  valeur_achat BIGINT  NOT NULL,
  valeur_vente BIGINT  NOT NULL,
  CONSTRAINT pilotage_stock_mensuel_unique UNIQUE (mois, produit_id, magasin_id)
);

