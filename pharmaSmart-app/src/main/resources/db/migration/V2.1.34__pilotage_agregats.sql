
CREATE TABLE IF NOT EXISTS pilotage_vente_ligne_jour
(
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jour              DATE        NOT NULL,
  produit_id        INTEGER     NOT NULL,
  magasin_id        INTEGER     NOT NULL,
  vendeur_id        INTEGER,
  nature_vente      VARCHAR(20),
  type_prescription VARCHAR(20),
  categorie_ca      VARCHAR(20) NOT NULL,
  quantite_demandee BIGINT      NOT NULL,
  quantite_servie   BIGINT      NOT NULL,
  quantite_avoir    BIGINT      NOT NULL,
  montant_ttc       BIGINT      NOT NULL,
  montant_ht        BIGINT      NOT NULL,
  remise            BIGINT      NOT NULL,
  cout_ttc          BIGINT      NOT NULL,
  cout_ht           BIGINT      NOT NULL,
  nb_lignes         BIGINT      NOT NULL
