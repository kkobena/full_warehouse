-- Promotions, phase 1 (docs/PLAN-GESTION-PROMOTIONS.md) : une remise datée, par magasin, sur une
-- liste d'articles, appliquée par le moteur sans saisie au comptoir. Elle remplit les mêmes champs
-- qu'une remise (discount_amount, taux_remise) : l'aval (ticket, FNE, CA, comptabilité) ne change pas.

-- Le statut porte la décision humaine ; « à venir / en cours / terminée » se lit sur les dates.
-- Aucun travail planifié n'ouvre ni ne ferme une promotion.
CREATE TABLE IF NOT EXISTS promotion
(
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                   VARCHAR(20)  UNIQUE,
  libelle                VARCHAR(100) NOT NULL,
  type                   VARCHAR(20)  NOT NULL,
  valeur                 INTEGER,
  date_debut             DATE         NOT NULL,
  date_fin               DATE         NOT NULL,
  statut                 VARCHAR(20)  NOT NULL DEFAULT 'BROUILLON',
  priorite               INTEGER      NOT NULL DEFAULT 0,
  quantite_min           INTEGER      NOT NULL DEFAULT 1,
  quantite_max_par_vente INTEGER,
  created_at             TIMESTAMP    NOT NULL DEFAULT NOW(),
  created_by_id          INTEGER REFERENCES app_user (id),
  updated_at             TIMESTAMP    NOT NULL DEFAULT NOW(),
  CONSTRAINT promotion_dates_ck CHECK (date_debut <= date_fin),
  CONSTRAINT promotion_type_ck CHECK (type IN ('PROMO_POURCENTAGE', 'PROMO_MONTANT', 'PROMO_PRIX_FIXE')),
  CONSTRAINT promotion_statut_ck CHECK (statut IN ('BROUILLON', 'VALIDEE', 'SUSPENDUE', 'ANNULEE')),
  CONSTRAINT promotion_quantite_min_ck CHECK (quantite_min >= 1),
  CONSTRAINT promotion_quantite_max_ck CHECK (quantite_max_par_vente IS NULL OR quantite_max_par_vente >= quantite_min)
);

COMMENT ON TABLE promotion IS
  'Promotion : remise datee, par magasin, sur une liste d''articles, posee par le moteur sans saisie.';
COMMENT ON COLUMN promotion.valeur IS
  'Taux en % (PROMO_POURCENTAGE) ou montant unitaire en F (PROMO_MONTANT) ; nul pour PROMO_PRIX_FIXE, dont le prix est par produit.';
COMMENT ON COLUMN promotion.statut IS
  'Decision humaine : BROUILLON, VALIDEE, SUSPENDUE, ANNULEE (definitif). L''etat en cours / terminee se lit sur les dates.';

-- Pas de magasin implicite : une promotion sans ligne ici ne s'applique nulle part.
CREATE TABLE IF NOT EXISTS promotion_magasin
(
  promotion_id BIGINT  NOT NULL REFERENCES promotion (id) ON DELETE CASCADE,
  magasin_id   INTEGER NOT NULL REFERENCES magasin (id),
  PRIMARY KEY (promotion_id, magasin_id)
);
CREATE INDEX IF NOT EXISTS promotion_magasin_magasin_idx ON promotion_magasin (magasin_id);

CREATE TABLE IF NOT EXISTS promotion_produit
(
  promotion_id BIGINT  NOT NULL REFERENCES promotion (id) ON DELETE CASCADE,
  produit_id   INTEGER NOT NULL REFERENCES produit (id),
  prix_promo   INTEGER,
  PRIMARY KEY (promotion_id, produit_id)
);
CREATE INDEX IF NOT EXISTS promotion_produit_produit_idx ON promotion_produit (produit_id);
COMMENT ON COLUMN promotion_produit.prix_promo IS 'Prix unitaire promotionnel, pour PROMO_PRIX_FIXE seulement.';

-- La ligne garde le lien et le libelle du moment : le ticket reste justifiable meme si la promotion
-- est renommee ensuite.
ALTER TABLE sales_line ADD COLUMN IF NOT EXISTS promotion_id BIGINT REFERENCES promotion (id);
ALTER TABLE sales_line ADD COLUMN IF NOT EXISTS promotion_libelle VARCHAR(100);
CREATE INDEX IF NOT EXISTS sales_line_promotion_idx ON sales_line (promotion_id) WHERE promotion_id IS NOT NULL;

COMMENT ON COLUMN sales_line.promotion_id IS
  'Promotion posee par le moteur. Nul pour une remise humaine : le moteur n''efface que ce qu''il a pose.';

-- Garde reglementaire : un article a TVA 0 (medicament a prix administre) n'est pas promouvable,
-- tant que l'officine n'en a pas decide autrement.
INSERT INTO app_configuration (name, value, description, created, updated, value_type)
VALUES ('APP_PROMOTION_TVA_ZERO_AUTORISEE', 'false',
        'Autoriser les promotions sur les articles a TVA 0 (medicaments a prix administre). Defaut : non.',
        NOW(), NOW(), 'BOOLEAN')
ON CONFLICT (name) DO NOTHING;

-- Menu : Referentiel > Promotions, a cote des remises. Le droit n'est accorde a aucun role ici
-- (l'ADMIN passe toujours) : c'est a l'officine de decider qui en dispose.
INSERT INTO nav_item (code, libelle, icon, router_link, parent_id, ordre, niveau, target_type, actif)
SELECT 'promotions', 'Promotions', 'pi pi-tags', '/promotions', id, 7, 2, 'ROUTE', TRUE
FROM nav_item
WHERE code = 'referentiel'
ON CONFLICT (code) DO NOTHING;
