-- Codes alternatifs d'un produit : GTIN du fabricant, EAN d'une autre boîte, code interne d'un
-- grossiste. Complète fournisseur_produit.code_cip / code_ean et produit.code_ean_labo, sans les
CREATE TABLE produit_code_alias
(
  id         integer generated by default as identity primary key,
  produit_id integer     NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
  code       varchar(20) NOT NULL,
  code_type  varchar(20) NOT NULL
    CONSTRAINT produit_code_alias_code_type_check
      CHECK (code_type IN ('GTIN_14', 'EAN_13', 'EAN_8', 'CIP_13', 'CIP_7', 'CUSTOM')),
  source     varchar(20) NOT NULL DEFAULT 'MANUAL'
    CONSTRAINT produit_code_alias_source_check
      CHECK (source IN ('MANUAL', 'AUTO_LEARNED', 'IMPORT')),
  created_at timestamp   NOT NULL DEFAULT now(),
  created_by varchar(50),
  -- Unicité par produit, pas globale : chez les grossistes ivoiriens deux conditionnements
  CONSTRAINT uq_produit_code_alias UNIQUE (produit_id, code)
);

CREATE INDEX idx_produit_code_alias_code ON produit_code_alias (code);
